/**
 * Full-screen WebView host for Whatsdeha.
 * Generated by Toolspea Android WebView App Builder.
 */
class MainActivity : AppCompatActivity() {

    private lateinit var webView: WebView
    private lateinit var swipeRefresh: SwipeRefreshLayout
    private lateinit var progressBar: ProgressBar
    private lateinit var offlineView: View
    private lateinit var contentRoot: ViewGroup

    private var loadFailed = false
    private var fileCallback: ValueCallback<Array<Uri>>? = null
    private var customView: View? = null
    private var customViewCallback: WebChromeClient.CustomViewCallback? = null
    private var pendingPermissionRequest: PermissionRequest? = null

    private val startUrl = "https://whatsdeha.blogspot.com/"

    /** Hosts kept inside the app. Everything else follows the external-link rule. */
    private val allowedHosts = listOf("whatsdeha.blogspot.com")

    private lateinit var fileChooserLauncher: ActivityResultLauncher<Intent>
    private val permissionLauncher =
        registerForActivityResult(ActivityResultContracts.RequestMultiplePermissions()) { results ->
            val request = pendingPermissionRequest
            pendingPermissionRequest = null
            if (request == null) return@registerForActivityResult
            if (results.values.all { it }) request.grant(request.resources) else request.deny()
        }

    @SuppressLint("SetJavaScriptEnabled")
    override fun onCreate(savedInstanceState: Bundle?) {
        val splash = installSplashScreen()
        super.onCreate(savedInstanceState)
        WindowCompat.setDecorFitsSystemWindows(window, false)
        setContentView(R.layout.activity_main)

        contentRoot = findViewById(R.id.content_root)
        webView = findViewById(R.id.web_view)
        swipeRefresh = findViewById(R.id.swipe_refresh)
        progressBar = findViewById(R.id.progress_bar)
        offlineView = findViewById(R.id.offline_view)
        findViewById<View>(R.id.retry_button).setOnClickListener { retry() }

        // Respect the status bar and gesture navigation instead of drawing under them.
        ViewCompat.setOnApplyWindowInsetsListener(contentRoot) { view, insets ->
            val bars = insets.getInsets(WindowInsetsCompat.Type.systemBars())
            view.setPadding(bars.left, bars.top, bars.right, bars.bottom)
            insets
        }

        fileChooserLauncher =
            registerForActivityResult(ActivityResultContracts.StartActivityForResult()) { result ->
                val callback = fileCallback
                fileCallback = null
                callback?.onReceiveValue(
                    WebChromeClient.FileChooserParams.parseResult(result.resultCode, result.data),
                )
            }

        configureWebView()
        registerBackHandling()

        if (savedInstanceState == null) webView.loadUrl(startUrl) else webView.restoreState(savedInstanceState)
    }

    private fun configureWebView() {
        val settings: WebSettings = webView.settings
        settings.javaScriptEnabled = true
        settings.domStorageEnabled = true
        settings.databaseEnabled = true
        settings.loadWithOverviewMode = true
        settings.useWideViewPort = true
        settings.builtInZoomControls = true
        settings.displayZoomControls = false
        settings.setSupportMultipleWindows(true)
        settings.javaScriptCanOpenWindowsAutomatically = true
        settings.mediaPlaybackRequiresUserGesture = false
        settings.setGeolocationEnabled(true)
        // Secure defaults: no file:// bridging, no mixed content.
        settings.allowFileAccess = false
        settings.allowContentAccess = false
        settings.mixedContentMode = WebSettings.MIXED_CONTENT_NEVER_ALLOW
        settings.cacheMode = WebSettings.LOAD_DEFAULT
        // Default Android WebView user agent is kept.

        CookieManager.getInstance().setAcceptCookie(true)
        CookieManager.getInstance().setAcceptThirdPartyCookies(webView, true)

        webView.isVerticalScrollBarEnabled = true
        webView.webViewClient = AppWebViewClient()
        webView.webChromeClient = AppChromeClient()

        webView.setDownloadListener(DownloadListener { url, userAgent, contentDisposition, mimeType, _ ->
            try {
                val request = DownloadManager.Request(Uri.parse(url))
                request.setMimeType(mimeType)
                request.addRequestHeader("User-Agent", userAgent)
                request.setNotificationVisibility(DownloadManager.Request.VISIBILITY_VISIBLE_NOTIFY_COMPLETED)
                val name = android.webkit.URLUtil.guessFileName(url, contentDisposition, mimeType)
                // Scoped storage: writes into the app's own Downloads entry, no storage permission needed.
                request.setDestinationInExternalFilesDir(this, android.os.Environment.DIRECTORY_DOWNLOADS, name)
                val manager = getSystemService(Context.DOWNLOAD_SERVICE) as DownloadManager
                manager.enqueue(request)
                Toast.makeText(this, getString(R.string.download_started, name), Toast.LENGTH_SHORT).show()
            } catch (e: Exception) {
                Toast.makeText(this, R.string.download_failed, Toast.LENGTH_SHORT).show()
            }
        })

        swipeRefresh.isEnabled = true
        swipeRefresh.setOnRefreshListener { webView.reload() }
        progressBar.visibility = View.GONE
    }

    private fun registerBackHandling() {
        onBackPressedDispatcher.addCallback(this, object : OnBackPressedCallback(true) {
            override fun handleOnBackPressed() {
                if (customView != null) {
                    (webView.webChromeClient as? AppChromeClient)?.onHideCustomView()
                    return
                }
                if (webView.canGoBack()) {
                    webView.goBack()
                    return
                }
                AlertDialog.Builder(this@MainActivity)
                    .setMessage(R.string.exit_confirm)
                    .setNegativeButton(R.string.cancel, null)
                    .setPositiveButton(R.string.exit) { _, _ -> finish() }
                    .show()
            }
        })
    }

    private fun retry() {
        loadFailed = false
        offlineView.visibility = View.GONE
        swipeRefresh.visibility = View.VISIBLE
        webView.loadUrl(startUrl)
    }

    private fun showOffline() {
        loadFailed = true
        swipeRefresh.visibility = View.GONE
        offlineView.visibility = View.VISIBLE
    }

    private fun isAllowedHost(host: String?): Boolean {
        val h = host?.lowercase()?.removePrefix("www.") ?: return false
        return allowedHosts.any { h == it || h.endsWith(".$it") }
    }

    private fun openExternally(uri: Uri) {
        try {
            startActivity(Intent(Intent.ACTION_VIEW, uri))
        } catch (e: ActivityNotFoundException) {
            Toast.makeText(this, R.string.no_app_for_link, Toast.LENGTH_SHORT).show()
        }
    }

    private inner class AppWebViewClient : WebViewClient() {
        override fun shouldOverrideUrlLoading(view: WebView, request: WebResourceRequest): Boolean {
            val uri = request.url
            val scheme = uri.scheme?.lowercase()
            if (scheme != null && scheme != "http" && scheme != "https") {
                // mailto:, tel:, intent:, upi: … always belong to another app.
                openExternally(uri)
                return true
            }
            if (isAllowedHost(uri.host)) return false
            openExternally(uri)
            return true
        }

        override fun onPageStarted(view: WebView, url: String, favicon: android.graphics.Bitmap?) {
            progressBar.visibility = View.VISIBLE
        }

        override fun onPageFinished(view: WebView, url: String) {
            progressBar.visibility = View.GONE
            swipeRefresh.isRefreshing = false
            if (!loadFailed) {
                swipeRefresh.visibility = View.VISIBLE
                offlineView.visibility = View.GONE
            }
        }

        override fun onReceivedError(view: WebView, request: WebResourceRequest, error: WebResourceError) {
            // Only a failed main-frame navigation should replace the UI.
            if (request.isForMainFrame) showOffline()
        }

        // NOTE: onReceivedSslError is deliberately NOT overridden. The platform
        // default cancels the load, which is the only safe behaviour. Never call
        // handler.proceed() here.
    }

    private inner class AppChromeClient : WebChromeClient() {
        override fun onProgressChanged(view: WebView, newProgress: Int) {
            progressBar.progress = newProgress
            if (newProgress >= 100) progressBar.visibility = View.GONE
        }

        override fun onShowFileChooser(
            webView: WebView,
            filePathCallback: ValueCallback<Array<Uri>>,
            fileChooserParams: FileChooserParams,
        ): Boolean {
            fileCallback?.onReceiveValue(null)
            fileCallback = filePathCallback
            return try {
                fileChooserLauncher.launch(fileChooserParams.createIntent())
                true
            } catch (e: ActivityNotFoundException) {
                fileCallback = null
                false
            }
        }

        override fun onPermissionRequest(request: PermissionRequest) {
            val needed = mutableListOf<String>()
            for (resource in request.resources) {
                when (resource) {
                    PermissionRequest.RESOURCE_VIDEO_CAPTURE -> needed.add(android.Manifest.permission.CAMERA)
                    PermissionRequest.RESOURCE_AUDIO_CAPTURE -> needed.add(android.Manifest.permission.RECORD_AUDIO)
                    else -> {}
                }
            }
            if (needed.isEmpty()) {
                request.deny()
                return
            }
            pendingPermissionRequest = request
            permissionLauncher.launch(needed.toTypedArray())
        }

        override fun onGeolocationPermissionsShowPrompt(origin: String, callback: GeolocationPermissions.Callback) {
            val granted = isAllowedHost(Uri.parse(origin).host)
            callback.invoke(origin, granted, false)
        }

        override fun onShowCustomView(view: View, callback: CustomViewCallback) {
            if (customView != null) {
                callback.onCustomViewHidden()
                return
            }
            customView = view
            customViewCallback = callback
            contentRoot.visibility = View.GONE
            (window.decorView as ViewGroup).addView(
                view,
                ViewGroup.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT),
            )
        }

        override fun onHideCustomView() {
            val view = customView ?: return
            (window.decorView as ViewGroup).removeView(view)
            customView = null
            contentRoot.visibility = View.VISIBLE
            customViewCallback?.onCustomViewHidden()
            customViewCallback = null
        }
    }

    override fun onSaveInstanceState(outState: Bundle) {
        super.onSaveInstanceState(outState)
        webView.saveState(outState)
    }

    override fun onPause() {
        super.onPause()
        webView.onPause()
    }

    override fun onResume() {
        super.onResume()
        webView.onResume()
    }

    override fun onDestroy() {
        webView.destroy()
        super.onDestroy()
    }
}
